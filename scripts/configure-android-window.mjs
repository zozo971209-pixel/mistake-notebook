import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const sourceRoot = resolve("src-tauri/gen/android/app/src/main/java");

function findMainActivity(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      const match = findMainActivity(path);
      if (match) return match;
    } else if (entry.name === "MainActivity.kt") {
      return path;
    }
  }
  return null;
}

if (!existsSync(sourceRoot)) {
  throw new Error(`Android source directory not found: ${sourceRoot}`);
}

const activityPath = findMainActivity(sourceRoot);
if (!activityPath) {
  throw new Error("MainActivity.kt was not generated by Tauri");
}

const currentSource = readFileSync(activityPath, "utf8");
const packageName = currentSource.match(/^package\s+([^\s]+)/m)?.[1];
if (!packageName) {
  throw new Error(`Unable to read package name from ${activityPath}`);
}

const safeAreaSource = `package ${packageName}

import android.os.Bundle
import android.view.View
import androidx.core.graphics.Insets
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import app.tauri.TauriActivity

class MainActivity : TauriActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)

    val contentView = findViewById<View>(android.R.id.content)
    ViewCompat.setOnApplyWindowInsetsListener(contentView) { view, windowInsets ->
      val safeAreaTypes =
        WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.displayCutout()
      val safeArea = windowInsets.getInsets(safeAreaTypes)

      view.setPadding(safeArea.left, safeArea.top, safeArea.right, safeArea.bottom)

      WindowInsetsCompat.Builder(windowInsets)
        .setInsets(safeAreaTypes, Insets.NONE)
        .build()
    }
    ViewCompat.requestApplyInsets(contentView)
  }
}
`;

writeFileSync(activityPath, safeAreaSource, "utf8");
console.log(`Configured Android safe areas in ${activityPath}`);
